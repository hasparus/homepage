import { readFileSync } from "node:fs";
import type * as React from "react";

import { jsonError } from "../src/lib/agents/http.js";
import { isValidOgToken } from "../src/lib/ogToken.js";

const author = {
  name: "Piotr Monwid-Olechnowicz",
  avatarSrc: "https://avatars.githubusercontent.com/u/15332326?v=4",
};

type Author = typeof author;

export default { fetch: og };

const width = 1200;
const height = 630;

const interRegular = readFileSync(
  new URL("../assets/og/Inter-Regular.ttf", import.meta.url),
);
const interBlack = readFileSync(
  new URL("../assets/og/Inter-Black.ttf", import.meta.url),
);

async function og(req: Request) {
  try {
    const url = new URL(req.url);
    const { post, stringifiedPost, token } = parseSearchParams(
      url.searchParams,
    );

    assertTokenIsValid(stringifiedPost, token);

    const { ImageResponse } =
      await import("@hasparus/definitely-not-vercel-og");

    console.log("returning ImageResponse for", stringifiedPost);

    const postImage = post.img;

    return new ImageResponse(
      h(
        "div",
        {
          tw: `
            w-full h-full
            flex flex-col
          `,
        },
        h(
          Illustration,
          { imageHref: postImage },
          postImage ? null : h(Title, { title: post.title, tw: `pb-28` }),
        ),
        h(Footer, { author, post, postImage }),
      ),
      {
        width,
        height,
        fonts: [
          {
            name: "Inter",
            data: interRegular,
            weight: 400,
            style: "normal",
          },
          {
            name: "Inter",
            data: interBlack,
            weight: 900,
            style: "normal",
          },
        ],
      },
    );
  } catch (err: unknown) {
    console.error(err);

    if (err instanceof HttpError) {
      return jsonError(
        err.status,
        err.status === 401 ? "INVALID_TOKEN" : "INVALID_PARAMETERS",
        err.message,
        "Use the image URL generated by the site without changing post or token.",
      );
    }

    return jsonError(
      500,
      "IMAGE_GENERATION_FAILED",
      "Couldn't generate the social image.",
      "Retry later or use https://haspar.us/og.png.",
    );
  }
}

function Illustration({
  children,
  imageHref,
  style,
}: {
  children?: React.ReactNode[];
  imageHref: string | null | undefined;
  style?: React.CSSProperties;
}) {
  imageHref = imageHref?.startsWith("/")
    ? `https://${process.env.VERCEL_URL}${imageHref}`
    : (imageHref ?? "");

  const searchParams = imageHref ? new URL(imageHref).searchParams : null;

  return h(
    "div",
    {
      tw: `
          absolute inset-0
          flex flex-1 justify-start items-end w-full pt-4 px-4 relative
          bg-[#171717]
        `,
    },
    !!imageHref &&
      h("img", {
        src: imageHref,
        width,
        height,
        style: {
          position: "absolute",
          inset: 0,
          objectFit: "cover",
          ...Object.fromEntries(searchParams || []),
          ...style,
        },
      }),
    ...(children || []),
  );
}

function Title({ title, tw }: { title: string; tw?: string }) {
  return h(
    "h1",
    {
      tw: `
        text-white text-8xl font-black z-10
        ${tw || ""}
      `,
    },
    title,
  );
}

function Footer({
  author,
  post,
  postImage,
}: {
  author: Author;
  post: Post;
  postImage?: string | null | undefined;
}) {
  return h(
    "div",
    {
      tw: `flex opacity-90 absolute bottom-0 left-0 right-0 h-28 overflow-hidden`,
    },
    postImage &&
      h(Illustration, {
        imageHref: postImage,
        style: {
          filter: "blur(6.4px)",
        },
      }),
    h(
      "footer",
      {
        tw: `
        absolute bottom-0 left-0 right-0
        h-28 w-full px-4 py-2.5
        bg-[rgba(10,10,10,0.5)]
        border-t-2 border-t-[rgba(255,255,255,0.1)]
        text-4xl
        flex flex-row justify-center items-center
      `,
      },
      h("img", {
        width: 80,
        height: 80,
        src: author.avatarSrc,
        tw: `rounded-full`,
      }),
      h("span", { tw: `ml-4 text-white` }, author.name),
      h("div", { tw: `flex-1` }),
      h(
        "span",
        { tw: `text-white` },
        [
          post.date.toLocaleDateString("sv-SE"),
          post.readingTimeMinutes > 2 && `${post.readingTimeMinutes} min read`,
        ]
          .filter(Boolean)
          .join(" · "),
      ),
    ),
  );
}

function h<T extends React.ElementType>(
  type: T,
  props: React.ComponentPropsWithRef<T>,
  ...children: React.ReactNode[]
) {
  return {
    type,
    key: "key" in props ? props.key : null,
    props: {
      ...props,
      children: children && children.length ? children : props.children,
    },
  };
}

type Post = {
  date: Date;
  title: string;
  readingTimeMinutes: number;
  img: string | null | undefined;
};

const SEPARATOR = "\t";
type SEPARATOR = typeof SEPARATOR;

// prettier-ignore
export type StringifiedPost = `${
  number /* timestamp */
}${SEPARATOR}${
  number /* reading time */
}${SEPARATOR}${
  string /* title */
}${SEPARATOR}${
  string /* picture */
}`;

export type OgFunctionSearchParams = {
  post: StringifiedPost;
  token?: string;
};

export function parseSearchParams(searchParams: URLSearchParams) {
  const stringifiedPost = (searchParams.get("post") || "") as StringifiedPost;

  const postArray = stringifiedPost.split(SEPARATOR);

  if (postArray.length !== 4) {
    throw new HttpError("Missing required search params.", 400);
  }

  const post: Post = {
    date: new Date(Number(postArray[0])),
    readingTimeMinutes: Math.round(Number(postArray[1])),
    title: postArray[2]!,
    img: postArray[3],
  };

  return {
    post,
    stringifiedPost,
    token: searchParams.get("token") || "",
  };
}

class HttpError extends Error {
  constructor(
    message: string,
    public readonly status: number,
  ) {
    super(message);
  }
}

function assertTokenIsValid(post: StringifiedPost, receivedToken: string) {
  const secret = process.env.OG_IMAGE_SECRET;

  if (!secret) {
    throw new Error("process.env.OG_IMAGE_SECRET is missing");
  }

  if (!isValidOgToken(secret, post, receivedToken)) {
    throw new HttpError("Invalid token.", 401);
  }
}
